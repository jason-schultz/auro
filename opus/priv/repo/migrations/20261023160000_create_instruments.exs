defmodule Opus.Repo.Migrations.CreateInstruments do
  use Ecto.Migration

  @moduledoc """
  The security master: one row per *listing* (RY on the TSX and RY on the
  NYSE are two rows), with the name each vendor knows it by and the feeds
  that store data for it. Every table that today carries an instrument as
  text (`candles.instrument`, `live_strategies.instrument`, …) is rekeyed
  onto `instruments.id` in later migrations; this one creates the table
  and fills it from the names already in the database plus the feed lists
  that used to live in `config/config.exs`.

  `symbol` is the bare listing symbol (`RY`, `XIU`, `SPY`, `EUR_USD`);
  `exchange` disambiguates dual listings. Vendor columns hold each vendor's
  spelling: OANDA `EUR_USD`, Questrade `RY.TO` / `SPY` (plus its numeric
  symbol id once looked up), Massive `BRK.B`. Wealthsimple positions use
  Questrade's spelling and are priced through Questrade, so they have no
  column of their own.

  US listings are seeded with the placeholder exchange `US`; the Rust
  enrich endpoint (`POST /api/instruments/enrich`) replaces it with the
  exchange Questrade reports.
  """

  # Feed memberships as of this migration. From here on the table is the
  # source; config.exs keeps only the feed parameters (days, granularities…).
  @questrade_bars ~w(
    HIVE.TO HUT.TO DMGI.VN DML.TO NXE.TO EFR.TO EQX.TO IMG.TO OGC.TO WDO.TO
    KNT.TO ARIS.TO SVM.TO ERO.TO TKO.TO CS.TO LUN.TO FL.VN WELL.TO BB.TO
    WEED.TO OGI.TO ACB.TO BTE.TO ATH.TO CJ.TO OBE.TO TVE.TO SDE.TO GOOS.TO
    BHC.TO DOO.TO AC.TO TFPM.TO SII.TO AYA.TO FVI.TO PAAS.TO XIU.TO
    SPY QQQ TSLA NVDA AMD PLTR SOFI AAPL AMZN META MSFT GOOGL NFLX COIN MSTR
    HOOD MARA RIOT SMCI ARM AVGO MU INTC F NIO RIVN LCID GME AMC SNAP UBER
    SHOP BABA BAC CCL AAL DKNG RBLX AFRM UPST IONQ RKLB SOUN CVNA
  )

  @massive_daily ~w(
    SPY QQQ IWM DIA EFA EEM TLT IEF GLD SLV USO XLE XLF XLK XLV XLY XLP XLI XLU
    XLB XLRE XME SMH KRE GDX EWJ EWG EWU EWC EWA FXI
    AAPL MSFT NVDA AMZN GOOGL META BRK.B AVGO TSLA LLY JPM V UNH XOM MA JNJ PG HD
    COST ABBV MRK WMT NFLX BAC CVX KO PEP ADBE CRM ORCL AMD TMO LIN MCD ACN CSCO
    ABT WFC DIS INTC IBM QCOM TXN DHR PM VZ AMGN NEE CAT GE INTU UNP HON LOW SPGI
    RTX AXP BKNG ISRG GS NKE MS T BLK PFE SBUX MDT C CVS DE ELV GILD MDLZ ADP AMT
    LMT BMY MO SCHW CI SO DUK CL TGT USB MMM COP BA UPS PYPL KHC GM F MET AIG EMR
    FDX CHTR COF BNY SPG GD
  )

  @options_chain ~w(SPY QQQ IWM AAPL MSFT NVDA AMZN GOOGL)

  # Listed funds among the seeded names; everything else listed is `equity`.
  @etfs ~w(
    SPY QQQ IWM DIA EFA EEM TLT IEF GLD SLV USO XLE XLF XLK XLV XLY XLP XLI XLU
    XLB XLRE XME SMH KRE GDX EWJ EWG EWU EWC EWA FXI XIU.TO
  )

  def up do
    execute(~S"""
    CREATE TABLE IF NOT EXISTS instruments (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        symbol VARCHAR(20) NOT NULL,
        exchange VARCHAR(12) NOT NULL,
        currency CHAR(3) NOT NULL,
        -- fx_major | fx_cross | metal | commodity | index | bond | equity | etf
        asset_class VARCHAR(12) NOT NULL,
        figi VARCHAR(12),
        active BOOLEAN NOT NULL DEFAULT TRUE,
        oanda_symbol VARCHAR(20),
        questrade_symbol VARCHAR(20),
        questrade_symbol_id BIGINT,
        massive_ticker VARCHAR(20),
        feed_questrade_bars BOOLEAN NOT NULL DEFAULT FALSE,
        feed_massive_daily BOOLEAN NOT NULL DEFAULT FALSE,
        feed_options_chain BOOLEAN NOT NULL DEFAULT FALSE,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        UNIQUE (symbol, exchange)
    );
    """)

    execute(
      "CREATE UNIQUE INDEX IF NOT EXISTS uq_instruments_oanda_symbol ON instruments (oanda_symbol) WHERE oanda_symbol IS NOT NULL;"
    )

    execute(
      "CREATE UNIQUE INDEX IF NOT EXISTS uq_instruments_questrade_symbol ON instruments (questrade_symbol) WHERE questrade_symbol IS NOT NULL;"
    )

    execute(
      "CREATE UNIQUE INDEX IF NOT EXISTS uq_instruments_massive_ticker ON instruments (massive_ticker) WHERE massive_ticker IS NOT NULL;"
    )

    execute("CREATE INDEX IF NOT EXISTS idx_instruments_symbol ON instruments (symbol);")

    seed_from_existing_names()
    flag_feeds()
  end

  def down do
    execute("DROP TABLE IF EXISTS instruments;")
  end

  # Every distinct name any table stores, classified by spelling: `A_B` is
  # an OANDA CFD, `.TO`/`.VN`/`.CN` are Canadian listings in Questrade
  # notation, anything else is a US listing. Every name on the feed lists
  # above already had rows when this was written, so the lists only flag;
  # a fresh (test) database gets an empty master.
  defp seed_from_existing_names do
    etfs = sql_list(@etfs)

    execute(
      ~S"""
      INSERT INTO instruments
          (symbol, exchange, currency, asset_class, active,
           oanda_symbol, questrade_symbol, massive_ticker)
      SELECT
          CASE WHEN name ~ '\.(TO|VN|CN)$' THEN regexp_replace(name, '\.(TO|VN|CN)$', '')
               ELSE name END,
          CASE WHEN name LIKE '%\_%' THEN 'OANDA'
               WHEN name LIKE '%.TO' THEN 'TSX'
               WHEN name LIKE '%.VN' THEN 'TSXV'
               WHEN name LIKE '%.CN' THEN 'CNSX'
               ELSE 'US' END,
          CASE WHEN name LIKE '%\_%' THEN split_part(name, '_', 2)
               WHEN name ~ '\.(TO|VN|CN)$' THEN 'CAD'
               ELSE 'USD' END,
          CASE WHEN name IN ('EUR_USD','GBP_USD','USD_JPY','USD_CHF','USD_CAD','AUD_USD','NZD_USD')
                   THEN 'fx_major'
               WHEN name ~ '^(XAU|XAG|XPT|XPD|XCU)_' THEN 'metal'
               WHEN name IN ('WTICO_USD','BCO_USD','NATGAS_USD','CORN_USD','WHEAT_USD','SOYBN_USD','SUGAR_USD')
                   THEN 'commodity'
               WHEN name IN ('UK100_GBP','EU50_EUR','DE30_EUR','FR40_EUR','NL25_EUR','CH20_CHF',
                             'AU200_AUD','JP225_USD','HK33_HKD','CN50_USD','SG30_SGD','US30_USD',
                             'SPX500_USD','NAS100_USD','US2000_USD','CHINAH_HKD','ESPIX_EUR','JP225Y_JPY')
                   THEN 'index'
               WHEN name ~ '^(USB[0-9]+Y|DE10YB|UK10YB)_' THEN 'bond'
               WHEN name LIKE '%\_%' THEN 'fx_cross'
      """ <>
        "         WHEN name IN (#{etfs}) THEN 'etf'\n" <>
        ~S"""
                 ELSE 'equity' END,
            -- OANDA names we have never streamed (financing rows for the whole
            -- account universe) start inactive; everything else is in use.
            CASE WHEN name LIKE '%\_%'
                  AND NOT EXISTS (SELECT 1 FROM candles c WHERE c.instrument = names.name)
                 THEN FALSE ELSE TRUE END,
            CASE WHEN name LIKE '%\_%' THEN name END,
            CASE WHEN name NOT LIKE '%\_%' THEN name END,
            CASE WHEN name NOT LIKE '%\_%' AND name !~ '\.(TO|VN|CN)$' THEN name END
        FROM (
            SELECT instrument AS name FROM candles GROUP BY instrument
            UNION SELECT instrument FROM live_strategies
            UNION SELECT instrument FROM live_trades
            UNION SELECT instrument FROM signal_events
            UNION SELECT instrument FROM strategy_configs
            UNION SELECT instrument FROM instrument_financing
            UNION SELECT instrument FROM instrument_risk_params
            UNION SELECT instrument FROM instrument_unit_caps
            UNION SELECT instrument FROM backtest_runs
            UNION SELECT instrument FROM strategies
            UNION SELECT underlying FROM option_contracts
            UNION SELECT symbol FROM wealthsimple_positions
        ) AS names
        WHERE name IS NOT NULL AND name <> ''
        ON CONFLICT (symbol, exchange) DO NOTHING;
        """
    )
  end

  defp flag_feeds do
    execute(
      "UPDATE instruments SET feed_questrade_bars = TRUE WHERE questrade_symbol IN (#{sql_list(@questrade_bars)});"
    )

    execute(
      "UPDATE instruments SET feed_massive_daily = TRUE WHERE massive_ticker IN (#{sql_list(@massive_daily)});"
    )

    execute(
      "UPDATE instruments SET feed_options_chain = TRUE WHERE questrade_symbol IN (#{sql_list(@options_chain)});"
    )
  end

  defp sql_list(names), do: Enum.map_join(Enum.uniq(names), ", ", &"'#{&1}'")
end
